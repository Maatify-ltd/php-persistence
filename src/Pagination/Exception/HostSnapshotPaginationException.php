<?php

declare(strict_types=1);

namespace Maatify\PhpPersistence\Pagination\Exception;

use Maatify\Exceptions\Contracts\ErrorCodeInterface;
use Maatify\Exceptions\Enum\ErrorCodeEnum;
use Maatify\Exceptions\Exception\System\SystemMaatifyException;
use Maatify\PhpPersistence\Exception\PhpPersistenceExceptionInterface;

/**
 * Reports a rejected Host snapshot request or an observation that prevents
 * confirming session, transaction or resource state. Driver and mapper
 * throwables retain their identity under the attempt's failure rules.
 */
final class HostSnapshotPaginationException extends SystemMaatifyException implements PhpPersistenceExceptionInterface
{
    protected function defaultErrorCode(): ErrorCodeInterface
    {
        return ErrorCodeEnum::MAATIFY_ERROR;
    }
}
